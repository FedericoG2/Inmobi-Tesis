-- =============================================================================
-- INMOBI — Registro de actividad del sistema
--
-- Objetivo: que el sistema muestre en todo momento qué pasó y en qué estado
-- quedaron las cosas ("Contrato creado", "Aumento aplicado", "Reclamo resuelto"…).
--
--   - Tabla public.actividad: un renglón por evento de negocio.
--   - Triggers en contratos, aumentos, reclamos, reclamo_eventos, propiedades,
--     propietarios, inquilinos y documentos: registran el evento solos, sin
--     depender del frontend (también quedan registrados los cambios hechos por
--     tareas automáticas, como la activación de contratos programados).
--   - RLS: el admin ve todo; el inquilino ve solo los eventos de sus contratos
--     marcados como visibles (alimentan las notificaciones del portal).
--   - Realtime: el dashboard y la campana del inquilino se actualizan en vivo.
--   - actividad_reconstruir(): regenera el historial a partir de los datos
--     existentes (se usa al instalar y en el seed de demo).
--
-- Ejecutar completo en Supabase → SQL Editor. Es idempotente.
-- =============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1) Tabla
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.actividad (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo text NOT NULL,
  entidad text NOT NULL,
  entidad_id bigint,
  titulo text NOT NULL,
  detalle text,
  inquilino_id bigint,
  contrato_id bigint,
  visible_inquilino boolean NOT NULL DEFAULT false,
  creado_por uuid DEFAULT auth.uid(),
  fecha_creacion timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.actividad IS
  'Historial de eventos del sistema (sin FKs a propósito: el evento sobrevive aunque se borre la entidad).';

CREATE INDEX IF NOT EXISTS idx_actividad_fecha ON public.actividad (fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS idx_actividad_inquilino ON public.actividad (inquilino_id, fecha_creacion DESC);

ALTER TABLE public.actividad ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Admin ve toda la actividad" ON public.actividad;
CREATE POLICY "Admin ve toda la actividad"
  ON public.actividad FOR SELECT TO authenticated
  USING (public.es_admin());

DROP POLICY IF EXISTS "Inquilino ve la actividad de sus contratos" ON public.actividad;
CREATE POLICY "Inquilino ve la actividad de sus contratos"
  ON public.actividad FOR SELECT TO authenticated
  USING (visible_inquilino AND inquilino_id = public.obtener_inquilino_id());

-- Las inserciones las hacen solo los triggers (SECURITY DEFINER): no hay política de INSERT.

-- ---------------------------------------------------------------------------
-- 2) Helpers de formato
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.actividad_monto(p_monto numeric)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN p_monto IS NULL THEN '—'
    ELSE '$ ' || replace(to_char(round(p_monto), 'FM999,999,999,990'), ',', '.') END;
$$;

CREATE OR REPLACE FUNCTION public.actividad_fecha(p_fecha date)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN p_fecha IS NULL THEN '—' ELSE to_char(p_fecha, 'DD/MM/YYYY') END;
$$;

CREATE OR REPLACE FUNCTION public.actividad_ajuste(p_tipo text, p_meses integer)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE lower(coalesce(p_tipo, ''))
      WHEN 'ipc' THEN 'IPC'
      WHEN 'icl' THEN 'ICL'
      WHEN 'porcentaje_fijo' THEN 'porcentaje fijo'
      WHEN '' THEN 'sin ajuste'
      ELSE p_tipo
    END
    || CASE WHEN p_meses IS NOT NULL AND p_meses > 0
         THEN ' cada ' || p_meses || CASE WHEN p_meses = 1 THEN ' mes' ELSE ' meses' END
         ELSE '' END;
$$;

CREATE OR REPLACE FUNCTION public.actividad_partes(p_inquilino_id bigint, p_propiedad_id bigint)
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT concat_ws(' · ',
    (SELECT nombre_completo FROM public.inquilinos WHERE id = p_inquilino_id),
    (SELECT direccion FROM public.propiedades WHERE id = p_propiedad_id));
$$;

CREATE OR REPLACE FUNCTION public.actividad_registrar(
  p_tipo text,
  p_entidad text,
  p_entidad_id bigint,
  p_titulo text,
  p_detalle text,
  p_inquilino_id bigint DEFAULT NULL,
  p_contrato_id bigint DEFAULT NULL,
  p_visible_inquilino boolean DEFAULT false,
  p_fecha timestamptz DEFAULT now()
) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.actividad (
    tipo, entidad, entidad_id, titulo, detalle,
    inquilino_id, contrato_id, visible_inquilino, fecha_creacion
  ) VALUES (
    p_tipo, p_entidad, p_entidad_id, p_titulo, nullif(btrim(coalesce(p_detalle, '')), ''),
    p_inquilino_id, p_contrato_id, coalesce(p_visible_inquilino, false), coalesce(p_fecha, now())
  );
END;
$$;

-- ---------------------------------------------------------------------------
-- 3) Contratos
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trg_actividad_contratos()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_partes text;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_partes := public.actividad_partes(NEW.inquilino_id, NEW.propiedad_id);
    IF NEW.estado = 'programado'::public.contrato_estado THEN
      PERFORM public.actividad_registrar(
        'contrato_programado', 'contrato', NEW.id, 'Contrato programado',
        v_partes || ' · inicia el ' || public.actividad_fecha(NEW.fecha_inicio)
          || '. La propiedad queda Reservada.',
        NEW.inquilino_id, NEW.id, true);
    ELSE
      PERFORM public.actividad_registrar(
        'contrato_creado', 'contrato', NEW.id, 'Contrato creado',
        v_partes || ' · ' || public.actividad_monto(NEW.monto_alquiler) || ' · '
          || public.actividad_ajuste(NEW.tipo_ajuste::text, NEW.periodicidad_meses) || '.',
        NEW.inquilino_id, NEW.id, true);
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
      v_partes := public.actividad_partes(NEW.inquilino_id, NEW.propiedad_id);
      IF OLD.estado = 'programado'::public.contrato_estado AND NEW.estado = 'activo'::public.contrato_estado THEN
        PERFORM public.actividad_registrar(
          'contrato_activado', 'contrato', NEW.id, 'Contrato en vigencia',
          v_partes || '. Comenzó la vigencia y la propiedad pasó a Alquilada.',
          NEW.inquilino_id, NEW.id, true);
      ELSIF OLD.estado = 'programado'::public.contrato_estado AND NEW.estado = 'inactivo'::public.contrato_estado THEN
        PERFORM public.actividad_registrar(
          'reserva_cancelada', 'contrato', NEW.id, 'Reserva cancelada',
          v_partes || '. La propiedad volvió a Disponible.',
          NEW.inquilino_id, NEW.id, true);
      ELSIF NEW.estado = 'inactivo'::public.contrato_estado THEN
        PERFORM public.actividad_registrar(
          'contrato_finalizado', 'contrato', NEW.id, 'Contrato finalizado',
          v_partes || '. La propiedad quedó liberada y el contrato sale de los aumentos.',
          NEW.inquilino_id, NEW.id, true);
      END IF;
    END IF;
    RETURN NEW;
  END IF;

  -- DELETE (anulación)
  PERFORM public.actividad_registrar(
    'contrato_anulado', 'contrato', OLD.id, 'Contrato anulado',
    public.actividad_partes(OLD.inquilino_id, OLD.propiedad_id) || '. Se eliminó junto con sus documentos.',
    OLD.inquilino_id, OLD.id, false);
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_actividad_contratos ON public.contratos;
CREATE TRIGGER trg_actividad_contratos
  AFTER INSERT OR UPDATE OF estado OR DELETE ON public.contratos
  FOR EACH ROW EXECUTE FUNCTION public.trg_actividad_contratos();

-- ---------------------------------------------------------------------------
-- 4) Aumentos
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.actividad_detalle_aumento(p_aumento public.aumentos)
RETURNS text LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_contrato public.contratos%ROWTYPE;
  v_pct text;
BEGIN
  SELECT * INTO v_contrato FROM public.contratos WHERE id = p_aumento.contrato_id;
  v_pct := CASE WHEN p_aumento.porcentaje_aplicado IS NOT NULL
    THEN ' (+' || replace(to_char(p_aumento.porcentaje_aplicado, 'FM990.0'), '.', ',') || '%)'
    ELSE '' END;
  RETURN concat_ws(' · ',
      (SELECT nombre_completo FROM public.inquilinos WHERE id = v_contrato.inquilino_id),
      public.actividad_monto(p_aumento.monto_anterior) || ' → ' || public.actividad_monto(p_aumento.monto_nuevo) || v_pct)
    || ' · rige desde el ' || public.actividad_fecha(p_aumento.fecha_aplicacion) || '.';
END;
$$;

CREATE OR REPLACE FUNCTION public.trg_actividad_aumentos()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_inquilino_id bigint;
BEGIN
  IF TG_OP = 'DELETE' THEN
    SELECT inquilino_id INTO v_inquilino_id FROM public.contratos WHERE id = OLD.contrato_id;
    PERFORM public.actividad_registrar(
      'aumento_deshecho', 'aumento', OLD.id, 'Aumento acordado cancelado',
      public.actividad_detalle_aumento(OLD) || ' El alquiler sigue con el monto vigente.',
      v_inquilino_id, OLD.contrato_id, true);
    RETURN OLD;
  END IF;

  SELECT inquilino_id INTO v_inquilino_id FROM public.contratos WHERE id = NEW.contrato_id;

  IF TG_OP = 'INSERT' THEN
    IF NEW.aplicado THEN
      PERFORM public.actividad_registrar(
        'aumento_aplicado', 'aumento', NEW.id, 'Aumento aplicado',
        public.actividad_detalle_aumento(NEW), v_inquilino_id, NEW.contrato_id, true);
    ELSE
      PERFORM public.actividad_registrar(
        'aumento_acordado', 'aumento', NEW.id, 'Aumento acordado',
        public.actividad_detalle_aumento(NEW), v_inquilino_id, NEW.contrato_id, true);
    END IF;
  ELSIF TG_OP = 'UPDATE' AND NEW.aplicado AND NOT OLD.aplicado THEN
    PERFORM public.actividad_registrar(
      'aumento_aplicado', 'aumento', NEW.id, 'Aumento en vigencia',
      public.actividad_detalle_aumento(NEW), v_inquilino_id, NEW.contrato_id, true);
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_actividad_aumentos ON public.aumentos;
CREATE TRIGGER trg_actividad_aumentos
  AFTER INSERT OR UPDATE OF aplicado OR DELETE ON public.aumentos
  FOR EACH ROW EXECUTE FUNCTION public.trg_actividad_aumentos();

-- ---------------------------------------------------------------------------
-- 5) Reclamos y su historial
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.actividad_estado_reclamo(p_estado text)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE p_estado WHEN 'Revision' THEN 'Revisión' ELSE p_estado END;
$$;

CREATE OR REPLACE FUNCTION public.trg_actividad_reclamos()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.actividad_registrar(
      'reclamo_creado', 'reclamo', NEW.id,
      CASE WHEN public.es_admin() THEN 'Reclamo creado' ELSE 'Nuevo reclamo del inquilino' END,
      concat_ws(' · ', '"' || NEW.titulo || '"', public.actividad_partes(NEW.inquilino_id, NEW.propiedad_id),
        'prioridad ' || NEW.prioridad::text) || '.',
      NEW.inquilino_id, NEW.contrato_id, true);
    RETURN NEW;
  END IF;

  PERFORM public.actividad_registrar(
    'reclamo_eliminado', 'reclamo', OLD.id, 'Reclamo eliminado',
    concat_ws(' · ', '"' || OLD.titulo || '"', public.actividad_partes(OLD.inquilino_id, OLD.propiedad_id)) || '.',
    OLD.inquilino_id, OLD.contrato_id, false);
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_actividad_reclamos ON public.reclamos;
CREATE TRIGGER trg_actividad_reclamos
  AFTER INSERT OR DELETE ON public.reclamos
  FOR EACH ROW EXECUTE FUNCTION public.trg_actividad_reclamos();

CREATE OR REPLACE FUNCTION public.trg_actividad_reclamo_eventos()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_reclamo public.reclamos%ROWTYPE;
  v_titulo text;
BEGIN
  -- El evento de creación (estado_anterior NULL) ya lo registra el trigger de reclamos.
  IF NEW.estado_anterior IS NULL AND NEW.estado_nuevo IS NOT NULL THEN
    RETURN NEW;
  END IF;

  SELECT * INTO v_reclamo FROM public.reclamos WHERE id = NEW.reclamo_id;
  IF NOT FOUND THEN
    RETURN NEW;
  END IF;

  IF NEW.estado_nuevo IS NOT NULL THEN
    v_titulo := CASE NEW.estado_nuevo::text
      WHEN 'Resuelto' THEN 'Reclamo resuelto'
      ELSE 'Reclamo en ' || public.actividad_estado_reclamo(NEW.estado_nuevo::text)
    END;
    PERFORM public.actividad_registrar(
      'reclamo_estado', 'reclamo', v_reclamo.id, v_titulo,
      concat_ws(' · ', '"' || v_reclamo.titulo || '"',
        (SELECT nombre_completo FROM public.inquilinos WHERE id = v_reclamo.inquilino_id),
        public.actividad_estado_reclamo(NEW.estado_anterior::text) || ' → '
          || public.actividad_estado_reclamo(NEW.estado_nuevo::text))
        || CASE WHEN NEW.comentario IS NOT NULL THEN '. ' || NEW.comentario ELSE '.' END,
      v_reclamo.inquilino_id, v_reclamo.contrato_id, true, NEW.fecha_creacion);
  ELSE
    PERFORM public.actividad_registrar(
      'reclamo_nota', 'reclamo', v_reclamo.id, 'Novedad en reclamo',
      '"' || v_reclamo.titulo || '": ' || coalesce(NEW.comentario, ''),
      v_reclamo.inquilino_id, v_reclamo.contrato_id, true, NEW.fecha_creacion);
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_actividad_reclamo_eventos ON public.reclamo_eventos;
CREATE TRIGGER trg_actividad_reclamo_eventos
  AFTER INSERT ON public.reclamo_eventos
  FOR EACH ROW EXECUTE FUNCTION public.trg_actividad_reclamo_eventos();

-- ---------------------------------------------------------------------------
-- 6) Cartera: propiedades, propietarios e inquilinos
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trg_actividad_propiedades()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.actividad_registrar(
      'propiedad_creada', 'propiedad', NEW.id, 'Propiedad agregada a la cartera',
      concat_ws(' · ', NEW.direccion, NEW.tipo::text, 'estado ' || NEW.estado::text) || '.');
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
      PERFORM public.actividad_registrar(
        'propiedad_estado', 'propiedad', NEW.id,
        CASE NEW.estado::text
          WHEN 'Mantenimiento' THEN 'Propiedad en mantenimiento'
          ELSE 'Propiedad ' || NEW.estado::text
        END,
        NEW.direccion || ' · ' || OLD.estado::text || ' → ' || NEW.estado::text || '.');
    END IF;
    RETURN NEW;
  END IF;

  PERFORM public.actividad_registrar(
    'propiedad_eliminada', 'propiedad', OLD.id, 'Propiedad eliminada', OLD.direccion || '.');
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_actividad_propiedades ON public.propiedades;
CREATE TRIGGER trg_actividad_propiedades
  AFTER INSERT OR UPDATE OF estado OR DELETE ON public.propiedades
  FOR EACH ROW EXECUTE FUNCTION public.trg_actividad_propiedades();

CREATE OR REPLACE FUNCTION public.trg_actividad_personas()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_entidad text := CASE TG_TABLE_NAME WHEN 'propietarios' THEN 'propietario' ELSE 'inquilino' END;
  v_label text := CASE TG_TABLE_NAME WHEN 'propietarios' THEN 'Propietario' ELSE 'Inquilino' END;
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM public.actividad_registrar(
      v_entidad || '_creado', v_entidad, NEW.id, v_label || ' registrado', NEW.nombre_completo || '.');
    RETURN NEW;
  END IF;

  PERFORM public.actividad_registrar(
    v_entidad || '_eliminado', v_entidad, OLD.id, v_label || ' eliminado', OLD.nombre_completo || '.');
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_actividad_propietarios ON public.propietarios;
CREATE TRIGGER trg_actividad_propietarios
  AFTER INSERT OR DELETE ON public.propietarios
  FOR EACH ROW EXECUTE FUNCTION public.trg_actividad_personas();

DROP TRIGGER IF EXISTS trg_actividad_inquilinos ON public.inquilinos;
CREATE TRIGGER trg_actividad_inquilinos
  AFTER INSERT OR DELETE ON public.inquilinos
  FOR EACH ROW EXECUTE FUNCTION public.trg_actividad_personas();

-- ---------------------------------------------------------------------------
-- 7) Documentos (contrato legal firmado)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trg_actividad_documentos()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_contrato public.contratos%ROWTYPE;
BEGIN
  IF coalesce(NEW.categoria::text, '') <> 'Contrato Firmado' OR NEW.contrato_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT * INTO v_contrato FROM public.contratos WHERE id = NEW.contrato_id;

  PERFORM public.actividad_registrar(
    'documento_subido', 'documento', NEW.id, 'Contrato firmado adjuntado',
    concat_ws(' · ', NEW.nombre, public.actividad_partes(v_contrato.inquilino_id, v_contrato.propiedad_id))
      || CASE WHEN NEW.visible_para_inquilino THEN '. Disponible en el portal del inquilino.' ELSE '. Solo administración.' END,
    v_contrato.inquilino_id, NEW.contrato_id, coalesce(NEW.visible_para_inquilino, false));
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_actividad_documentos ON public.documentos;
CREATE TRIGGER trg_actividad_documentos
  AFTER INSERT ON public.documentos
  FOR EACH ROW EXECUTE FUNCTION public.trg_actividad_documentos();

-- ---------------------------------------------------------------------------
-- 8) Reconstrucción del historial a partir de los datos existentes.
--    Borra la tabla y la regenera con fechas reales (aumentos, reclamos,
--    eventos de reclamos) o aproximadas (inicio/fin de contratos).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.actividad_reconstruir()
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  r record;
  v_total integer;
BEGIN
  IF auth.uid() IS NOT NULL AND NOT public.es_admin() THEN
    RAISE EXCEPTION 'Solo un administrador puede reconstruir la actividad.';
  END IF;

  DELETE FROM public.actividad;

  -- Contratos: alta (a la fecha de inicio, o hoy si es programado) y fin.
  FOR r IN SELECT * FROM public.contratos LOOP
    PERFORM public.actividad_registrar(
      CASE WHEN r.estado = 'programado'::public.contrato_estado THEN 'contrato_programado' ELSE 'contrato_creado' END,
      'contrato', r.id,
      CASE WHEN r.estado = 'programado'::public.contrato_estado THEN 'Contrato programado' ELSE 'Contrato creado' END,
      public.actividad_partes(r.inquilino_id, r.propiedad_id) || ' · '
        || public.actividad_monto(r.monto_inicial) || ' · '
        || public.actividad_ajuste(r.tipo_ajuste::text, r.periodicidad_meses)
        || CASE WHEN r.estado = 'programado'::public.contrato_estado
             THEN ' · inicia el ' || public.actividad_fecha(r.fecha_inicio) ELSE '' END || '.',
      r.inquilino_id, r.id, true,
      CASE WHEN r.estado = 'programado'::public.contrato_estado
        THEN now() - interval '2 days'
        ELSE r.fecha_inicio::timestamptz + interval '10 hours' END);

    IF r.estado = 'inactivo'::public.contrato_estado AND r.fecha_fin <= CURRENT_DATE THEN
      PERFORM public.actividad_registrar(
        'contrato_finalizado', 'contrato', r.id, 'Contrato finalizado',
        public.actividad_partes(r.inquilino_id, r.propiedad_id) || '. La propiedad quedó liberada.',
        r.inquilino_id, r.id, true, r.fecha_fin::timestamptz + interval '18 hours');
    END IF;
  END LOOP;

  -- Aumentos con su fecha real de confirmación.
  FOR r IN SELECT a.*, c.inquilino_id AS inq FROM public.aumentos a JOIN public.contratos c ON c.id = a.contrato_id LOOP
    PERFORM public.actividad_registrar(
      CASE WHEN r.aplicado THEN 'aumento_aplicado' ELSE 'aumento_acordado' END,
      'aumento', r.id,
      CASE WHEN r.aplicado THEN 'Aumento aplicado' ELSE 'Aumento acordado' END,
      public.actividad_detalle_aumento((SELECT a2 FROM public.aumentos a2 WHERE a2.id = r.id)),
      r.inq, r.contrato_id, true, r.fecha_creacion);
  END LOOP;

  -- Reclamos y cambios de estado / notas.
  FOR r IN SELECT * FROM public.reclamos LOOP
    PERFORM public.actividad_registrar(
      'reclamo_creado', 'reclamo', r.id, 'Reclamo creado',
      concat_ws(' · ', '"' || r.titulo || '"', public.actividad_partes(r.inquilino_id, r.propiedad_id),
        'prioridad ' || r.prioridad::text) || '.',
      r.inquilino_id, r.contrato_id, true, r.fecha_creacion);
  END LOOP;

  FOR r IN
    SELECT e.*, rc.titulo, rc.inquilino_id, rc.contrato_id
    FROM public.reclamo_eventos e
    JOIN public.reclamos rc ON rc.id = e.reclamo_id
    WHERE e.estado_anterior IS NOT NULL OR e.estado_nuevo IS NULL
  LOOP
    IF r.estado_nuevo IS NOT NULL THEN
      PERFORM public.actividad_registrar(
        'reclamo_estado', 'reclamo', r.reclamo_id,
        CASE r.estado_nuevo::text WHEN 'Resuelto' THEN 'Reclamo resuelto'
          ELSE 'Reclamo en ' || public.actividad_estado_reclamo(r.estado_nuevo::text) END,
        concat_ws(' · ', '"' || r.titulo || '"',
          (SELECT nombre_completo FROM public.inquilinos WHERE id = r.inquilino_id),
          public.actividad_estado_reclamo(r.estado_anterior::text) || ' → '
            || public.actividad_estado_reclamo(r.estado_nuevo::text))
          || CASE WHEN r.comentario IS NOT NULL THEN '. ' || r.comentario ELSE '.' END,
        r.inquilino_id, r.contrato_id, true, r.fecha_creacion);
    ELSE
      PERFORM public.actividad_registrar(
        'reclamo_nota', 'reclamo', r.reclamo_id, 'Novedad en reclamo',
        '"' || r.titulo || '": ' || coalesce(r.comentario, ''),
        r.inquilino_id, r.contrato_id, true, r.fecha_creacion);
    END IF;
  END LOOP;

  SELECT count(*) INTO v_total FROM public.actividad;
  RETURN v_total;
END;
$$;

-- Permisos: Supabase otorga EXECUTE a anon/authenticated por defecto. Las funciones
-- SECURITY DEFINER internas no deben poder llamarse por RPC (expondrían nombres y
-- direcciones de otros inquilinos, o permitirían inventar eventos).
REVOKE ALL ON FUNCTION public.actividad_registrar(text, text, bigint, text, text, bigint, bigint, boolean, timestamptz)
  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.actividad_partes(bigint, bigint) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.actividad_detalle_aumento(public.aumentos) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.trg_actividad_contratos() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.trg_actividad_aumentos() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.trg_actividad_reclamos() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.trg_actividad_reclamo_eventos() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.trg_actividad_propiedades() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.trg_actividad_personas() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.trg_actividad_documentos() FROM PUBLIC, anon, authenticated;

-- Reconstruir: solo admin (la función además lo valida adentro).
REVOKE ALL ON FUNCTION public.actividad_reconstruir() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.actividad_reconstruir() TO authenticated;

-- Historial inicial (solo si la tabla está vacía).
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.actividad) THEN
    PERFORM public.actividad_reconstruir();
  END IF;
END $$;

COMMIT;

-- ---------------------------------------------------------------------------
-- 9) Realtime (fuera de la transacción: ALTER PUBLICATION no siempre se permite dentro)
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime')
     AND NOT EXISTS (
       SELECT 1 FROM pg_publication_tables
       WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'actividad'
     ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.actividad;
  END IF;
END $$;
