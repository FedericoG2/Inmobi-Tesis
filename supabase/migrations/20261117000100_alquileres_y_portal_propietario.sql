RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF NEW.raw_app_meta_data ->> 'rol' IN ('admin', 'encargado', 'inquilino', 'propietario') THEN
