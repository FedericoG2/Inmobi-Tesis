  FOR DELETE TO authenticated
  USING (
    bucket_id = 'comprobantes-pago'
    AND (owner = (SELECT auth.uid()) OR owner_id = (SELECT auth.uid())::text)
    AND NOT public.comprobante_pago_registrado(name)
  );

