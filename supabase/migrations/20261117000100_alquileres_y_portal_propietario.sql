-- ---------------------------------------------------------------------------
-- 2) Períodos de alquiler
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.periodos_alquiler (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contrato_id bigint NOT NULL REFERENCES public.contratos (id) ON DELETE RESTRICT,
  periodo date NOT NULL CHECK (extract(day FROM periodo) = 1),
  fecha_vencimiento date,
  monto numeric NOT NULL CHECK (monto >= 0),
  estado text NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente', 'Pagado')),
  fecha_confirmacion timestamptz,
  confirmado_por uuid,
  fecha_creacion timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT periodos_alquiler_contrato_periodo_key UNIQUE (contrato_id, periodo),
  CONSTRAINT periodos_alquiler_confirmacion_check CHECK ((estado = 'Pagado') = (fecha_confirmacion IS NOT NULL))
);

COMMENT ON TABLE public.periodos_alquiler IS
  'Un renglón por mes de alquiler de cada contrato. Solo el Encargado de Alquileres lo pasa a Pagado.';

CREATE INDEX IF NOT EXISTS idx_periodos_alquiler_estado ON public.periodos_alquiler (estado, periodo);

-- Mes en letras para los mensajes: "abril 2026".
CREATE OR REPLACE FUNCTION public.nombre_periodo(p_periodo date)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT (ARRAY['enero', 'febrero', 'marzo', 'abril', 'mayo', 'junio', 'julio', 'agosto',
                'septiembre', 'octubre', 'noviembre', 'diciembre'])[extract(month FROM p_periodo)::int]
         || ' ' || extract(year FROM p_periodo)::int;
$$;

-- Vencimiento del mes: el día de pago del contrato, sin pasarse del último día del mes.
CREATE OR REPLACE FUNCTION public.vencimiento_periodo(p_periodo date, p_dia smallint)
RETURNS date
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE WHEN p_dia IS NULL THEN NULL
    ELSE p_periodo + (least(p_dia::int,
           extract(day FROM (p_periodo + interval '1 month' - interval '1 day'))::int) - 1)
  END;
$$;

-- Monto que regía en un mes: el del último aumento aplicado hasta ese mes inclusive;
-- antes del primer aumento, el monto inicial del contrato.
CREATE OR REPLACE FUNCTION public.monto_vigente_contrato(p_contrato_id bigint, p_periodo date)
RETURNS numeric
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT coalesce(
    (SELECT a.monto_nuevo FROM public.aumentos a
      WHERE a.contrato_id = p_contrato_id AND a.fecha_aplicacion < p_periodo + interval '1 month'
      ORDER BY a.fecha_aplicacion DESC LIMIT 1),
    (SELECT a.monto_anterior FROM public.aumentos a
      WHERE a.contrato_id = p_contrato_id
      ORDER BY a.fecha_aplicacion LIMIT 1),
    (SELECT coalesce(c.monto_inicial, c.monto_alquiler) FROM public.contratos c WHERE c.id = p_contrato_id)
  );
$$;

-- Crea los períodos que falten de los contratos activos, desde el mes de inicio hasta el mes
-- en curso (o el del fin del contrato). Es idempotente. El Encargado genera los de toda la
-- cartera; el inquilino y el propietario, solo los de sus contratos (los mismos que verían).
CREATE OR REPLACE FUNCTION public.generar_periodos_alquiler(p_contrato_id bigint DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_creados integer;
  v_todos boolean := auth.uid() IS NULL OR public.es_encargado();
BEGIN
  INSERT INTO public.periodos_alquiler (contrato_id, periodo, fecha_vencimiento, monto)
  SELECT c.id, m.mes::date,
         public.vencimiento_periodo(m.mes::date, c.dia_vencimiento),
         public.monto_vigente_contrato(c.id, m.mes::date)
  FROM public.contratos c
  CROSS JOIN LATERAL generate_series(
    date_trunc('month', c.fecha_inicio::timestamp),
    date_trunc('month', least(c.fecha_fin, public.fecha_hoy_ar())::timestamp),
    interval '1 month'
  ) AS m(mes)
  WHERE c.estado = 'activo'::public.contrato_estado
    AND (p_contrato_id IS NULL OR c.id = p_contrato_id)
    AND (v_todos
         OR c.inquilino_id = public.obtener_inquilino_id()
         OR c.propiedad_id IN (SELECT public.propiedades_del_propietario()))
  ON CONFLICT ON CONSTRAINT periodos_alquiler_contrato_periodo_key DO NOTHING;

  GET DIAGNOSTICS v_creados = ROW_COUNT;
  RETURN v_creados;
END;
$$;

-- Un contrato que empieza (alta activa o activación de uno programado) recibe sus períodos.
CREATE OR REPLACE FUNCTION public.trg_contratos_generar_periodos()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.estado = 'activo'::public.contrato_estado
     AND (TG_OP = 'INSERT' OR OLD.estado IS DISTINCT FROM NEW.estado) THEN
    PERFORM public.generar_periodos_alquiler(NEW.id);
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_contratos_generar_periodos ON public.contratos;
CREATE TRIGGER trg_contratos_generar_periodos
  AFTER INSERT OR UPDATE OF estado ON public.contratos
  FOR EACH ROW EXECUTE FUNCTION public.trg_contratos_generar_periodos();

