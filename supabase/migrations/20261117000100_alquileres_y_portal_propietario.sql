-- INMOBI — Módulo de Alquileres y portal del Propietario (alcance 1.3, versión final)
--
--   1. Cuenta del propietario vinculada a su ficha y funciones de acceso por rol.
--   2. Períodos de alquiler: uno por mes de cada contrato, desde el inicio hasta el mes
--      en curso (o el fin del contrato). Estado Pendiente o Pagado.
--   3. Comprobantes de pago: el inquilino o el Encargado los registran para un período
--      Pendiente. Registrar un comprobante no paga el período.
--   4. Confirmar y deshacer el pago de un período: solo el Encargado de Alquileres, y solo
--      si el período tiene al menos un comprobante.
--   5. Aumentos y períodos: al confirmar un aumento, los períodos pendientes desde su mes
--      toman el monto nuevo; no se deshace un aumento si ese período ya está pagado.
--   6. Reglas del alcance que faltaban en la base: un contrato con períodos o comprobantes
--      no se elimina; la identidad del propietario y de la propiedad con historial no
--      cambia; un reclamo Resuelto no se edita.
--   7. Permisos (RLS) del inquilino y del propietario, y Storage de los comprobantes.
--   8. Registro de actividad de los pagos y generación diaria de períodos.
--
-- Requiere 20261117000000_rol_propietario.sql y 20261008_actividad_sistema.sql.
-- Ejecutar completo en Supabase → SQL Editor. Es idempotente.
