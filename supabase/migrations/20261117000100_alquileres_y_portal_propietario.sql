-- 3) Comprobantes de pago
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.comprobantes_pago (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  periodo_id bigint NOT NULL REFERENCES public.periodos_alquiler (id) ON DELETE RESTRICT,
  contrato_id bigint NOT NULL REFERENCES public.contratos (id) ON DELETE RESTRICT,
  nombre text NOT NULL,
  url_archivo text NOT NULL UNIQUE,
  monto numeric CHECK (monto IS NULL OR monto > 0),
  fecha_pago date,
  observaciones text,
  cargado_por uuid DEFAULT auth.uid(),
  fecha_subida timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.comprobantes_pago IS
  'Comprobantes de pago de un período. No se modifican ni se eliminan (trazabilidad).';

CREATE INDEX IF NOT EXISTS idx_comprobantes_pago_periodo ON public.comprobantes_pago (periodo_id);
CREATE INDEX IF NOT EXISTS idx_comprobantes_pago_contrato ON public.comprobantes_pago (contrato_id);

-- Quién puede registrar un comprobante para un período: el Encargado, si está Pendiente;
-- el inquilino, si además es de su contrato y el contrato está activo.
CREATE OR REPLACE FUNCTION public.puede_registrar_comprobante(p_periodo_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.periodos_alquiler p
    JOIN public.contratos c ON c.id = p.contrato_id
    WHERE p.id = p_periodo_id
      AND p.estado = 'Pendiente'
      AND (public.es_encargado()
           OR (c.inquilino_id = public.obtener_inquilino_id()
               AND c.estado = 'activo'::public.contrato_estado))
  );
$$;

-- Los archivos se guardan como "<id del período>/<archivo>" en el bucket comprobantes-pago.
CREATE OR REPLACE FUNCTION public.puede_subir_archivo_comprobante(p_ruta text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT CASE
    WHEN split_part(p_ruta, '/', 1) ~ '^[0-9]{1,18}$'
      THEN public.puede_registrar_comprobante(split_part(p_ruta, '/', 1)::bigint)
    ELSE false
  END;
$$;

CREATE OR REPLACE FUNCTION public.comprobante_pago_registrado(p_ruta text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (SELECT 1 FROM public.comprobantes_pago WHERE url_archivo = p_ruta);
$$;

CREATE OR REPLACE FUNCTION public.validar_comprobante_pago()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v record;
BEGIN
  SELECT p.estado, p.contrato_id, c.estado AS estado_contrato, c.inquilino_id
  INTO v
  FROM public.periodos_alquiler p
  JOIN public.contratos c ON c.id = p.contrato_id
  WHERE p.id = NEW.periodo_id
  FOR SHARE OF p;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El período de alquiler no existe' USING ERRCODE = 'P0001';
  END IF;
  IF v.estado <> 'Pendiente' THEN
    RAISE EXCEPTION 'Solo se pueden registrar comprobantes para períodos pendientes de pago'
      USING ERRCODE = 'P0001';
  END IF;
  IF auth.uid() IS NOT NULL AND NOT public.es_encargado() THEN
    IF v.inquilino_id IS DISTINCT FROM public.obtener_inquilino_id() THEN
      RAISE EXCEPTION 'Solo podés registrar comprobantes de tus propios contratos' USING ERRCODE = 'P0001';
    END IF;
    IF v.estado_contrato <> 'activo'::public.contrato_estado THEN
      RAISE EXCEPTION 'Solo se pueden registrar comprobantes de contratos activos' USING ERRCODE = 'P0001';
    END IF;
  END IF;
  IF split_part(NEW.url_archivo, '/', 1) <> NEW.periodo_id::text THEN
    RAISE EXCEPTION 'El archivo no corresponde al período indicado' USING ERRCODE = 'P0001';
  END IF;

  NEW.contrato_id := v.contrato_id;
  NEW.cargado_por := auth.uid();
  NEW.fecha_subida := now();
  NEW.nombre := left(btrim(NEW.nombre), 200);
  NEW.observaciones := nullif(left(btrim(coalesce(NEW.observaciones, '')), 500), '');
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_comprobantes_pago_validar ON public.comprobantes_pago;
CREATE TRIGGER trg_comprobantes_pago_validar
  BEFORE INSERT ON public.comprobantes_pago
  FOR EACH ROW EXECUTE FUNCTION public.validar_comprobante_pago();

-- ---------------------------------------------------------------------------
-- 4) Confirmar y deshacer el pago de un período
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.detalle_periodo_actividad(p_periodo public.periodos_alquiler)
RETURNS text
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT concat_ws(' · ',
    (SELECT public.actividad_partes(c.inquilino_id, c.propiedad_id) FROM public.contratos c WHERE c.id = p_periodo.contrato_id),
    public.nombre_periodo(p_periodo.periodo),
    public.actividad_monto(p_periodo.monto));
$$;

CREATE OR REPLACE FUNCTION public.confirmar_pago_periodo(p_periodo_id bigint)
RETURNS public.periodos_alquiler
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_periodo public.periodos_alquiler;
BEGIN
  IF NOT public.es_encargado() THEN
    RAISE EXCEPTION 'Solo el Encargado de Alquileres puede confirmar pagos' USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO v_periodo FROM public.periodos_alquiler WHERE id = p_periodo_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'El período de alquiler no existe' USING ERRCODE = 'P0001';
  END IF;
  IF v_periodo.estado = 'Pagado' THEN
    RAISE EXCEPTION 'El pago de este período ya está confirmado' USING ERRCODE = 'P0001';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.comprobantes_pago WHERE periodo_id = p_periodo_id) THEN
    RAISE EXCEPTION 'No se puede confirmar el pago: el período no tiene comprobantes de pago registrados'
      USING ERRCODE = 'P0001';
  END IF;

  UPDATE public.periodos_alquiler
  SET estado = 'Pagado', fecha_confirmacion = now(), confirmado_por = auth.uid()
  WHERE id = p_periodo_id
  RETURNING * INTO v_periodo;

  PERFORM public.actividad_registrar(
    'pago_confirmado', 'pago', v_periodo.id, 'Pago confirmado',
    public.detalle_periodo_actividad(v_periodo) || '.',
    (SELECT inquilino_id FROM public.contratos WHERE id = v_periodo.contrato_id),
    v_periodo.contrato_id, true);

  RETURN v_periodo;
END;
$$;

CREATE OR REPLACE FUNCTION public.deshacer_pago_periodo(p_periodo_id bigint)
RETURNS public.periodos_alquiler
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_periodo public.periodos_alquiler;
BEGIN
  IF NOT public.es_encargado() THEN
    RAISE EXCEPTION 'Solo el Encargado de Alquileres puede deshacer la confirmación de un pago'
      USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO v_periodo FROM public.periodos_alquiler WHERE id = p_periodo_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'El período de alquiler no existe' USING ERRCODE = 'P0001';
  END IF;
  IF v_periodo.estado <> 'Pagado' THEN
    RAISE EXCEPTION 'El período no tiene un pago confirmado' USING ERRCODE = 'P0001';
  END IF;

  UPDATE public.periodos_alquiler
  SET estado = 'Pendiente', fecha_confirmacion = NULL, confirmado_por = NULL
  WHERE id = p_periodo_id
  RETURNING * INTO v_periodo;

  PERFORM public.actividad_registrar(
    'pago_deshecho', 'pago', v_periodo.id, 'Confirmación de pago deshecha',
    public.detalle_periodo_actividad(v_periodo) || '. El período volvió a Pendiente.',
    (SELECT inquilino_id FROM public.contratos WHERE id = v_periodo.contrato_id),
    v_periodo.contrato_id, true);

  RETURN v_periodo;
END;
$$;

-- Registro de actividad al cargar un comprobante (aparece en la campana del Encargado).
CREATE OR REPLACE FUNCTION public.trg_actividad_comprobantes_pago()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_periodo public.periodos_alquiler;
  v_inquilino bigint;
BEGIN
  SELECT * INTO v_periodo FROM public.periodos_alquiler WHERE id = NEW.periodo_id;
  SELECT inquilino_id INTO v_inquilino FROM public.contratos WHERE id = NEW.contrato_id;
  PERFORM public.actividad_registrar(
    'pago_comprobante', 'pago', NEW.periodo_id, 'Comprobante de pago registrado',
    public.detalle_periodo_actividad(v_periodo)
      || CASE WHEN public.es_encargado() THEN ' · cargado por la inmobiliaria.' ELSE ' · cargado por el inquilino.' END,
    v_inquilino, NEW.contrato_id, true, NEW.fecha_subida);
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_actividad_comprobantes_pago ON public.comprobantes_pago;
CREATE TRIGGER trg_actividad_comprobantes_pago
  AFTER INSERT ON public.comprobantes_pago
  FOR EACH ROW EXECUTE FUNCTION public.trg_actividad_comprobantes_pago();

-- Reconstrucción de la actividad de pagos (la llama actividad_reconstruir).
CREATE OR REPLACE FUNCTION public.actividad_reconstruir_pagos()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT cp.*, c.inquilino_id, perf.rol AS rol_autor
    FROM public.comprobantes_pago cp
    JOIN public.contratos c ON c.id = cp.contrato_id
    LEFT JOIN public.perfiles perf ON perf.id = cp.cargado_por
  LOOP
    PERFORM public.actividad_registrar(
      'pago_comprobante', 'pago', r.periodo_id, 'Comprobante de pago registrado',
      public.detalle_periodo_actividad((SELECT p FROM public.periodos_alquiler p WHERE p.id = r.periodo_id))
        || CASE WHEN r.rol_autor = 'encargado' THEN ' · cargado por la inmobiliaria.' ELSE ' · cargado por el inquilino.' END,
      r.inquilino_id, r.contrato_id, true, r.fecha_subida);
  END LOOP;

  FOR r IN
    SELECT p, c.inquilino_id, p.fecha_confirmacion
    FROM public.periodos_alquiler p
    JOIN public.contratos c ON c.id = p.contrato_id
    WHERE p.estado = 'Pagado'
  LOOP
    PERFORM public.actividad_registrar(
      'pago_confirmado', 'pago', (r.p).id, 'Pago confirmado',
      public.detalle_periodo_actividad(r.p) || '.',
      r.inquilino_id, (r.p).contrato_id, true, r.fecha_confirmacion);
  END LOOP;
END;
$$;

-- ---------------------------------------------------------------------------
-- 5) Aumentos y períodos
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.trg_aumentos_periodos()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_mes date;
  v_pagado date;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_mes := date_trunc('month', NEW.fecha_aplicacion::timestamp)::date;
    UPDATE public.periodos_alquiler
    SET monto = NEW.monto_nuevo
    WHERE contrato_id = NEW.contrato_id AND estado = 'Pendiente' AND periodo >= v_mes;
    RETURN NEW;
  END IF;

  -- Deshacer: el monto anterior vuelve a los períodos pendientes, salvo que ya se haya
  -- cobrado un período con el monto nuevo.
  v_mes := date_trunc('month', OLD.fecha_aplicacion::timestamp)::date;
  SELECT min(periodo) INTO v_pagado
  FROM public.periodos_alquiler
  WHERE contrato_id = OLD.contrato_id AND estado = 'Pagado' AND periodo >= v_mes;

  IF v_pagado IS NOT NULL THEN
    RAISE EXCEPTION 'No se puede deshacer el aumento: el período de % ya está pagado', public.nombre_periodo(v_pagado)
      USING ERRCODE = 'P0001';
  END IF;

  UPDATE public.periodos_alquiler
  SET monto = OLD.monto_anterior
  WHERE contrato_id = OLD.contrato_id AND estado = 'Pendiente' AND periodo >= v_mes;
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_aumentos_periodos_alta ON public.aumentos;
CREATE TRIGGER trg_aumentos_periodos_alta
  AFTER INSERT ON public.aumentos
  FOR EACH ROW EXECUTE FUNCTION public.trg_aumentos_periodos();

DROP TRIGGER IF EXISTS trg_aumentos_periodos_baja ON public.aumentos;
CREATE TRIGGER trg_aumentos_periodos_baja
  BEFORE DELETE ON public.aumentos
  FOR EACH ROW EXECUTE FUNCTION public.trg_aumentos_periodos();

-- ---------------------------------------------------------------------------
-- 6) Reglas del alcance que faltaban en la base
-- ---------------------------------------------------------------------------

-- Contratos: solo se eliminan finalizados o programados y sin aumentos, períodos de
-- alquiler, comprobantes ni reclamos del mismo inquilino sobre la propiedad.
CREATE OR REPLACE FUNCTION public.bloquear_delete_contrato_con_movimientos()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF OLD.estado = 'activo'::public.contrato_estado THEN
    RAISE EXCEPTION 'No se puede eliminar un contrato activo. Finalizalo primero.'
      USING ERRCODE = 'P0001';
  END IF;

  IF EXISTS (SELECT 1 FROM public.aumentos WHERE contrato_id = OLD.id)
     OR EXISTS (SELECT 1 FROM public.periodos_alquiler WHERE contrato_id = OLD.id)
     OR EXISTS (SELECT 1 FROM public.comprobantes_pago WHERE contrato_id = OLD.id)
     OR EXISTS (
       SELECT 1 FROM public.reclamos
       WHERE inquilino_id = OLD.inquilino_id AND propiedad_id = OLD.propiedad_id
     ) THEN
    RAISE EXCEPTION 'No se puede eliminar el contrato porque tiene movimientos asociados (aumentos, períodos de alquiler, comprobantes o reclamos)'
      USING ERRCODE = 'P0001';
  END IF;

  RETURN OLD;
END;
$$;

-- Propietarios: con propiedades asociadas no cambian el tipo de persona ni el documento.
CREATE OR REPLACE FUNCTION public.bloquear_cambio_identidad_propietario()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF (NEW.tipo_persona, NEW.dni_cuit) IS DISTINCT FROM (OLD.tipo_persona, OLD.dni_cuit)
     AND EXISTS (SELECT 1 FROM public.propiedades WHERE propietario_id = OLD.id) THEN
    RAISE EXCEPTION 'El propietario tiene propiedades asociadas: no se puede cambiar el tipo de persona ni el DNI/CUIT'
      USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_propietarios_bloquear_cambio_identidad ON public.propietarios;
CREATE TRIGGER trg_propietarios_bloquear_cambio_identidad
  BEFORE UPDATE OF tipo_persona, dni_cuit ON public.propietarios
  FOR EACH ROW EXECUTE FUNCTION public.bloquear_cambio_identidad_propietario();

-- Propiedades: con contratos o reclamos asociados no cambian el tipo ni la dirección.
CREATE OR REPLACE FUNCTION public.bloquear_cambio_identidad_propiedad()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF (lower(btrim(coalesce(NEW.tipo, ''))), lower(btrim(coalesce(NEW.calle, ''))),
      lower(btrim(coalesce(NEW.altura, ''))), lower(btrim(coalesce(NEW.piso, ''))),
      lower(btrim(coalesce(NEW.unidad, ''))), lower(btrim(coalesce(NEW.ciudad, ''))))
     IS DISTINCT FROM
     (lower(btrim(coalesce(OLD.tipo, ''))), lower(btrim(coalesce(OLD.calle, ''))),
      lower(btrim(coalesce(OLD.altura, ''))), lower(btrim(coalesce(OLD.piso, ''))),
      lower(btrim(coalesce(OLD.unidad, ''))), lower(btrim(coalesce(OLD.ciudad, ''))))
     AND (EXISTS (SELECT 1 FROM public.contratos WHERE propiedad_id = OLD.id)
          OR EXISTS (SELECT 1 FROM public.reclamos WHERE propiedad_id = OLD.id)) THEN
    RAISE EXCEPTION 'La propiedad tiene contratos o reclamos asociados: no se puede cambiar el tipo ni la dirección'
      USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_propiedades_bloquear_cambio_identidad ON public.propiedades;
CREATE TRIGGER trg_propiedades_bloquear_cambio_identidad
  BEFORE UPDATE OF tipo, calle, altura, piso, unidad, ciudad ON public.propiedades
  FOR EACH ROW EXECUTE FUNCTION public.bloquear_cambio_identidad_propiedad();

-- Reclamos: el Encargado edita los que están Pendiente, En Proceso o Revisión. Un Resuelto
-- solo cambia al reabrirlo desde la gestión.
CREATE OR REPLACE FUNCTION public.validar_reclamo_modificacion()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_gestion boolean := coalesce(current_setting('inmobi.gestion_reclamo', true), '') = 'on';
BEGIN
  IF NEW.estado IS DISTINCT FROM OLD.estado AND NOT v_gestion THEN
    RAISE EXCEPTION 'El estado del reclamo solo se cambia desde la gestion'
      USING ERRCODE = 'P0001';
  END IF;
  IF OLD.estado = 'Resuelto' AND NOT v_gestion THEN
    RAISE EXCEPTION 'Un reclamo resuelto no se modifica. Reabrilo desde la gestión para continuar'
      USING ERRCODE = 'P0001';
  END IF;
  IF (NEW.inquilino_id, NEW.propiedad_id, NEW.contrato_id)
     IS DISTINCT FROM (OLD.inquilino_id, OLD.propiedad_id, OLD.contrato_id) THEN
    RAISE EXCEPTION 'Solo se pueden modificar titulo, descripcion, categoria y prioridad'
      USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;

-- Adjuntos de reclamo: hasta 5 imágenes y no sobre un reclamo Resuelto.
CREATE OR REPLACE FUNCTION public.validar_cantidad_adjuntos_reclamo()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.reclamo_id IS NULL THEN
    RETURN NEW;
  END IF;
  IF EXISTS (SELECT 1 FROM public.reclamos WHERE id = NEW.reclamo_id AND estado = 'Resuelto') THEN
    RAISE EXCEPTION 'No se pueden agregar imagenes a un reclamo resuelto'
      USING ERRCODE = 'P0001';
  END IF;
  IF (SELECT count(*) FROM public.documentos WHERE reclamo_id = NEW.reclamo_id) >= 5 THEN
    RAISE EXCEPTION 'Un reclamo admite hasta 5 imagenes'
      USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;

