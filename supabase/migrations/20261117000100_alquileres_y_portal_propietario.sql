-- Descarga: quien puede ver la fila del comprobante (la RLS de comprobantes_pago decide).
-- Quien subió un archivo que no llegó a registrarse también lo ve, para poder borrarlo
-- (Storage lee la fila antes de borrarla).
DROP POLICY IF EXISTS comprobantes_storage_select ON storage.objects;
CREATE POLICY comprobantes_storage_select ON storage.objects
  FOR SELECT TO authenticated
  USING (
    bucket_id = 'comprobantes-pago'
    AND (
      EXISTS (SELECT 1 FROM public.comprobantes_pago cp WHERE cp.url_archivo = objects.name)
      OR ((owner = (SELECT auth.uid()) OR owner_id = (SELECT auth.uid())::text)
          AND NOT public.comprobante_pago_registrado(name))
    )
  );

-- Solo se borra un archivo propio que no llegó a registrarse (si falló el alta de la fila).
DROP POLICY IF EXISTS comprobantes_storage_delete_huerfano ON storage.objects;
