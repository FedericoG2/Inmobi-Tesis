-- Cada día (00:10 de Argentina) se activan los contratos programados que empiezan y se
-- crean los períodos del mes. Las pantallas también los generan al abrirse.
DO $cron$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    PERFORM cron.unschedule(jobid) FROM cron.job WHERE jobname = 'generar-periodos-alquiler';
    PERFORM cron.schedule(
      'generar-periodos-alquiler',
      '10 3 * * *',
      'SELECT public.activar_contratos_programados(); SELECT public.generar_periodos_alquiler();'
    );
  END IF;
END;
$cron$;

