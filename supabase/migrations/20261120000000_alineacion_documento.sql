-- 4) Revisión de aumentos pendientes
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.revisiones_aumento (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contrato_id bigint NOT NULL REFERENCES public.contratos (id) ON DELETE CASCADE,
  fecha_aplicacion date NOT NULL,
  revisado boolean NOT NULL DEFAULT false,
  observaciones text CHECK (observaciones IS NULL OR length(observaciones) <= 500),
  monto_ajustado numeric CHECK (monto_ajustado IS NULL OR monto_ajustado > 0),
  actualizado_por uuid DEFAULT auth.uid(),
  actualizado_en timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT revisiones_aumento_contrato_fecha_key UNIQUE (contrato_id, fecha_aplicacion)
);

COMMENT ON TABLE public.revisiones_aumento IS
  'Marca de revisado, observaciones y redondeo de un aumento pendiente, hasta que se confirma.';

-- Al confirmar el aumento, su revisión ya quedó copiada en el aumento: se borra.
CREATE OR REPLACE FUNCTION public.trg_aumentos_cerrar_revision()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  DELETE FROM public.revisiones_aumento
  WHERE contrato_id = NEW.contrato_id AND fecha_aplicacion = NEW.fecha_aplicacion;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_aumentos_cerrar_revision ON public.aumentos;
CREATE TRIGGER trg_aumentos_cerrar_revision
  AFTER INSERT ON public.aumentos
  FOR EACH ROW EXECUTE FUNCTION public.trg_aumentos_cerrar_revision();

ALTER TABLE public.revisiones_aumento ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS revisiones_aumento_encargado ON public.revisiones_aumento;
CREATE POLICY revisiones_aumento_encargado ON public.revisiones_aumento
  FOR ALL TO authenticated
  USING (public.es_encargado()) WITH CHECK (public.es_encargado());

REVOKE ALL ON public.revisiones_aumento FROM anon;
REVOKE TRUNCATE ON public.revisiones_aumento FROM PUBLIC, authenticated;

-- ---------------------------------------------------------------------------
-- 5) Pago con aumento pendiente (RF-057)
-- ---------------------------------------------------------------------------
-- Mes del aumento que todavía falta confirmar y que afecta al período (o NULL si no hay).
CREATE OR REPLACE FUNCTION public.aumento_pendiente_del_periodo(p_contrato_id bigint, p_periodo date)
RETURNS date
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT date_trunc('month', c.fecha_proximo_aumento::timestamp)::date
  FROM public.contratos c
  WHERE c.id = p_contrato_id
    AND c.estado = 'activo'::public.contrato_estado
    AND c.fecha_proximo_aumento IS NOT NULL
    AND c.fecha_proximo_aumento <= c.fecha_fin
    AND date_trunc('month', c.fecha_proximo_aumento::timestamp)::date <= p_periodo;
$$;

CREATE OR REPLACE FUNCTION public.confirmar_pago_periodo(p_periodo_id bigint)
RETURNS public.periodos_alquiler
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_periodo public.periodos_alquiler;
  v_aumento date;
BEGIN
  IF NOT public.es_encargado() THEN
    RAISE EXCEPTION 'Solo el Encargado de Alquileres puede confirmar pagos' USING ERRCODE = 'P0001';
  END IF;

  SELECT * INTO v_periodo FROM public.periodos_alquiler WHERE id = p_periodo_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'El período de alquiler no existe' USING ERRCODE = 'P0001';
  END IF;
  IF v_periodo.estado = 'Pagado' THEN
    RAISE EXCEPTION 'El pago de este período ya está confirmado' USING ERRCODE = 'P0001';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.comprobantes_pago WHERE periodo_id = p_periodo_id) THEN
    RAISE EXCEPTION 'No se puede confirmar el pago: el período no tiene comprobantes de pago registrados'
      USING ERRCODE = 'P0001';
  END IF;

  v_aumento := public.aumento_pendiente_del_periodo(v_periodo.contrato_id, v_periodo.periodo);
  IF v_aumento IS NOT NULL THEN
    RAISE EXCEPTION 'No se puede confirmar el pago de %: falta confirmar el aumento de %',
      public.nombre_periodo(v_periodo.periodo), public.nombre_periodo(v_aumento)
      USING ERRCODE = 'P0001';
  END IF;

  UPDATE public.periodos_alquiler
  SET estado = 'Pagado', fecha_confirmacion = now(), confirmado_por = auth.uid()
  WHERE id = p_periodo_id
  RETURNING * INTO v_periodo;

  PERFORM public.actividad_registrar(
    'pago_confirmado', 'pago', v_periodo.id, 'Pago confirmado',
    public.detalle_periodo_actividad(v_periodo) || '.',
    (SELECT inquilino_id FROM public.contratos WHERE id = v_periodo.contrato_id),
    v_periodo.contrato_id, true);

  RETURN v_periodo;
END;
$$;

-- ---------------------------------------------------------------------------
-- 6) Períodos hasta el mes que se elige en Alquileres
-- ---------------------------------------------------------------------------
-- Sin p_hasta se generan hasta el mes en curso. El Encargado puede pedir un mes posterior
-- (por ejemplo, para registrar un pago adelantado); los portales nunca pasan del mes en curso.
DROP FUNCTION IF EXISTS public.generar_periodos_alquiler(bigint);
CREATE OR REPLACE FUNCTION public.generar_periodos_alquiler(p_contrato_id bigint DEFAULT NULL, p_hasta date DEFAULT NULL)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_creados integer;
  v_todos boolean := auth.uid() IS NULL OR public.es_encargado();
  v_hasta date := public.fecha_hoy_ar();
BEGIN
  IF p_hasta IS NOT NULL AND p_hasta > v_hasta AND v_todos THEN
    v_hasta := (date_trunc('month', p_hasta::timestamp) + interval '1 month' - interval '1 day')::date;
  END IF;

  INSERT INTO public.periodos_alquiler (contrato_id, periodo, fecha_vencimiento, monto)
  SELECT c.id, m.mes::date,
         public.vencimiento_periodo(m.mes::date, c.dia_vencimiento),
         public.monto_vigente_contrato(c.id, m.mes::date)
  FROM public.contratos c
  CROSS JOIN LATERAL generate_series(
    date_trunc('month', c.fecha_inicio::timestamp),
    date_trunc('month', least(c.fecha_fin, v_hasta)::timestamp),
    interval '1 month'
  ) AS m(mes)
  WHERE c.estado = 'activo'::public.contrato_estado
    AND (p_contrato_id IS NULL OR c.id = p_contrato_id)
    AND (v_todos
         OR c.inquilino_id = public.obtener_inquilino_id()
         OR c.propiedad_id IN (SELECT public.propiedades_del_propietario()))
  ON CONFLICT ON CONSTRAINT periodos_alquiler_contrato_periodo_key DO NOTHING;

  GET DIAGNOSTICS v_creados = ROW_COUNT;
  RETURN v_creados;
END;
$$;

-- ---------------------------------------------------------------------------
-- 7) Auditoría en las tablas del alcance (al final, para no registrar la carga inicial)
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['contratos', 'periodos_alquiler', 'aumentos', 'comprobantes_pago', 'reclamos']
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_auditoria ON public.%I', t);
    EXECUTE format(
      'CREATE TRIGGER trg_auditoria AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.trg_auditoria()',
      t
    );
  END LOOP;
END $$;

