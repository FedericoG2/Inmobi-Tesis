-- 2) Cierre de contratos
-- ---------------------------------------------------------------------------
ALTER TABLE public.contratos
  ADD COLUMN IF NOT EXISTS motivo_cierre text,
  ADD COLUMN IF NOT EXISTS observaciones_cierre text,
  ADD COLUMN IF NOT EXISTS cerrado_en timestamptz;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'contratos_motivo_cierre_check') THEN
    ALTER TABLE public.contratos
      ADD CONSTRAINT contratos_motivo_cierre_check
      CHECK (motivo_cierre IS NULL OR motivo_cierre IN ('Finalizado', 'Rescindido', 'Cancelado'));
  END IF;
END $$;

-- Contratos cerrados antes de esta migración: una reserva que nunca empezó fue cancelada;
-- el resto se toma como finalizado.
UPDATE public.contratos c
SET motivo_cierre = CASE
      WHEN c.fecha_inicio > coalesce(c.updated_at, c.fecha_creacion)::date
           AND NOT EXISTS (SELECT 1 FROM public.periodos_alquiler p WHERE p.contrato_id = c.id)
        THEN 'Cancelado'
      ELSE 'Finalizado'
    END,
    cerrado_en = coalesce(c.updated_at, c.fecha_creacion, now())
WHERE c.estado = 'inactivo'::public.contrato_estado AND c.motivo_cierre IS NULL;

-- Al cerrar: un programado se cancela; un activo se finaliza o se rescinde. El cierre no se edita.
CREATE OR REPLACE FUNCTION public.validar_cierre_contrato()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.estado = 'inactivo'::public.contrato_estado AND OLD.estado IS DISTINCT FROM NEW.estado THEN
    IF OLD.estado = 'programado'::public.contrato_estado THEN
      IF NEW.motivo_cierre IS NOT NULL AND NEW.motivo_cierre <> 'Cancelado' THEN
        RAISE EXCEPTION 'Un contrato programado se cancela: todavía no empezó, no se finaliza ni se rescinde'
          USING ERRCODE = 'P0001';
      END IF;
      NEW.motivo_cierre := 'Cancelado';
    ELSE
      IF NEW.motivo_cierre = 'Cancelado' THEN
        RAISE EXCEPTION 'Solo se cancela un contrato programado. Un contrato activo se finaliza o se rescinde'
          USING ERRCODE = 'P0001';
      END IF;
      NEW.motivo_cierre := coalesce(NEW.motivo_cierre, 'Finalizado');
    END IF;
    NEW.cerrado_en := now();
    NEW.observaciones_cierre := nullif(left(btrim(coalesce(NEW.observaciones_cierre, '')), 500), '');
  ELSIF NEW.estado <> 'inactivo'::public.contrato_estado THEN
    NEW.motivo_cierre := NULL;
    NEW.observaciones_cierre := NULL;
    NEW.cerrado_en := NULL;
  ELSIF (NEW.motivo_cierre, NEW.observaciones_cierre, NEW.cerrado_en)
        IS DISTINCT FROM (OLD.motivo_cierre, OLD.observaciones_cierre, OLD.cerrado_en) THEN
    RAISE EXCEPTION 'Los datos del cierre de un contrato no se modifican' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_contratos_validar_cierre ON public.contratos;
CREATE TRIGGER trg_contratos_validar_cierre
  BEFORE UPDATE ON public.contratos
  FOR EACH ROW EXECUTE FUNCTION public.validar_cierre_contrato();

-- La actividad del cierre dice si se finalizó, se rescindió o se canceló.
CREATE OR REPLACE FUNCTION public.trg_actividad_contratos()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_partes text;
  v_nota text;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_partes := public.actividad_partes(NEW.inquilino_id, NEW.propiedad_id);
    IF NEW.estado = 'programado'::public.contrato_estado THEN
      PERFORM public.actividad_registrar(
        'contrato_programado', 'contrato', NEW.id, 'Contrato programado',
        v_partes || ' · inicia el ' || public.actividad_fecha(NEW.fecha_inicio)
          || '. La propiedad queda Reservada.',
        NEW.inquilino_id, NEW.id, true);
    ELSE
      PERFORM public.actividad_registrar(
        'contrato_creado', 'contrato', NEW.id, 'Contrato creado',
        v_partes || ' · ' || public.actividad_monto(NEW.monto_alquiler) || ' · '
          || public.actividad_ajuste(NEW.tipo_ajuste::text, NEW.periodicidad_meses) || '.',
        NEW.inquilino_id, NEW.id, true);
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE' THEN
    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
      v_partes := public.actividad_partes(NEW.inquilino_id, NEW.propiedad_id);
      v_nota := CASE WHEN NEW.observaciones_cierre IS NOT NULL THEN ' ' || NEW.observaciones_cierre ELSE '' END;
      IF OLD.estado = 'programado'::public.contrato_estado AND NEW.estado = 'activo'::public.contrato_estado THEN
        PERFORM public.actividad_registrar(
          'contrato_activado', 'contrato', NEW.id, 'Contrato en vigencia',
          v_partes || '. Comenzó la vigencia y la propiedad pasó a Alquilada.',
          NEW.inquilino_id, NEW.id, true);
      ELSIF NEW.motivo_cierre = 'Cancelado' THEN
        PERFORM public.actividad_registrar(
          'reserva_cancelada', 'contrato', NEW.id, 'Contrato cancelado',
          v_partes || '. El contrato programado se canceló y la propiedad volvió a Disponible.' || v_nota,
          NEW.inquilino_id, NEW.id, true);
      ELSIF NEW.motivo_cierre = 'Rescindido' THEN
        PERFORM public.actividad_registrar(
          'contrato_rescindido', 'contrato', NEW.id, 'Contrato rescindido',
          v_partes || '. Rescisión anticipada: la propiedad quedó Disponible.' || v_nota,
          NEW.inquilino_id, NEW.id, true);
      ELSIF NEW.estado = 'inactivo'::public.contrato_estado THEN
        PERFORM public.actividad_registrar(
          'contrato_finalizado', 'contrato', NEW.id, 'Contrato finalizado',
          v_partes || '. La propiedad quedó Disponible y el contrato sale de los aumentos.' || v_nota,
          NEW.inquilino_id, NEW.id, true);
      END IF;
    END IF;
    RETURN NEW;
  END IF;

  PERFORM public.actividad_registrar(
    'contrato_anulado', 'contrato', OLD.id, 'Contrato eliminado',
    public.actividad_partes(OLD.inquilino_id, OLD.propiedad_id) || '. Se eliminó junto con sus documentos.',
    OLD.inquilino_id, OLD.id, false);
  RETURN OLD;
END;
$$;

-- ---------------------------------------------------------------------------
-- 3) Índices cargados a mano
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.indices_manuales (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo public.indice_referencia NOT NULL,
  anio smallint NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
  mes smallint NOT NULL CHECK (mes BETWEEN 1 AND 12),
  fecha date,
  valor numeric NOT NULL,
  cargado_por uuid DEFAULT auth.uid(),
  fecha_carga timestamptz NOT NULL DEFAULT now(),
  -- IPC: variación porcentual del mes (sin fecha). ICL: valor del índice en una fecha.
  CONSTRAINT indices_manuales_forma_check CHECK (
    (tipo = 'ipc' AND fecha IS NULL AND valor > -100 AND valor < 100)
    OR (tipo = 'icl' AND fecha IS NOT NULL AND valor > 0
        AND anio = extract(year FROM fecha) AND mes = extract(month FROM fecha))
  )
);

COMMENT ON TABLE public.indices_manuales IS
  'IPC (variación % mensual) o ICL (valor diario) cargados a mano cuando Argly no publica el dato.';

CREATE UNIQUE INDEX IF NOT EXISTS indices_manuales_ipc_mes ON public.indices_manuales (anio, mes) WHERE tipo = 'ipc';
CREATE UNIQUE INDEX IF NOT EXISTS indices_manuales_icl_fecha ON public.indices_manuales (fecha) WHERE tipo = 'icl';

ALTER TABLE public.indices_manuales ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS indices_manuales_encargado ON public.indices_manuales;
CREATE POLICY indices_manuales_encargado ON public.indices_manuales
  FOR ALL TO authenticated
  USING (public.es_encargado()) WITH CHECK (public.es_encargado());

REVOKE ALL ON public.indices_manuales FROM anon;
REVOKE TRUNCATE ON public.indices_manuales FROM PUBLIC, authenticated;

