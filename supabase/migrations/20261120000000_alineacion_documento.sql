-- INMOBI — Alineación con el documento final (secciones 8 a 11)
--
--   1. Auditoría (tabla auditoria): cada alta, modificación y baja de contratos, períodos de
--      alquiler, aumentos, comprobantes de pago y reclamos, con el usuario, la fecha y los
--      valores anteriores y posteriores.
--   2. Cierre de contratos: Finalizado, Rescindido (rescisión anticipada) o Cancelado (un
--      contrato programado), con observaciones y fecha de cierre (CU-010 y CU-011).
--   3. Índices cargados a mano (tabla indices_manuales, CU-024): IPC por mes o ICL por fecha,
--      para cuando Argly no publica el valor. Sirven para todos los aumentos que los usan.
--   4. Revisión de aumentos (Pendiente → Revisado → Confirmado): la marca de revisado, las
--      observaciones y el redondeo quedan guardados hasta confirmar (CU-025 a CU-027).
--   5. No se confirma el pago de un período si a ese mes le corresponde un aumento que
--      todavía no fue confirmado (RF-057).
--   6. El Encargado puede abrir en Alquileres un mes posterior: se generan sus períodos.
--
-- Requiere 20261117000100_alquileres_y_portal_propietario.sql. Es idempotente.
-- =============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1) Auditoría
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.auditoria (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id uuid,
  tabla text NOT NULL,
  registro_id bigint,
  operacion text NOT NULL CHECK (operacion IN ('alta', 'modificacion', 'baja')),
  valor_anterior jsonb,
  valor_nuevo jsonb,
  creado_en timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.auditoria IS
  'Altas, modificaciones y bajas de contratos, períodos, aumentos, comprobantes y reclamos. No se borra.';

CREATE INDEX IF NOT EXISTS idx_auditoria_registro ON public.auditoria (tabla, registro_id, creado_en DESC);

-- Registra el cambio con los valores completos de la fila antes y después.
CREATE OR REPLACE FUNCTION public.trg_auditoria()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_anterior jsonb;
  v_nuevo jsonb;
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN v_anterior := to_jsonb(OLD); END IF;
  IF TG_OP IN ('UPDATE', 'INSERT') THEN v_nuevo := to_jsonb(NEW); END IF;
  IF TG_OP = 'UPDATE' AND v_anterior = v_nuevo THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.auditoria (usuario_id, tabla, registro_id, operacion, valor_anterior, valor_nuevo)
  VALUES (
    auth.uid(),
    TG_TABLE_NAME,
    (coalesce(v_nuevo, v_anterior) ->> 'id')::bigint,
    CASE TG_OP WHEN 'INSERT' THEN 'alta' WHEN 'UPDATE' THEN 'modificacion' ELSE 'baja' END,
    v_anterior,
    v_nuevo
  );
  RETURN coalesce(NEW, OLD);
END;
$$;

-- Historial de cambios de un contrato y de lo que depende de él, con el email de quien lo hizo.
CREATE OR REPLACE FUNCTION public.auditoria_contrato(p_contrato_id bigint)
RETURNS TABLE (
  id bigint, tabla text, registro_id bigint, operacion text,
  valor_anterior jsonb, valor_nuevo jsonb, creado_en timestamptz, usuario_email text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT a.id, a.tabla, a.registro_id, a.operacion, a.valor_anterior, a.valor_nuevo, a.creado_en, u.email::text
  FROM public.auditoria a
  LEFT JOIN auth.users u ON u.id = a.usuario_id
  WHERE public.es_encargado()
    AND (
      (a.tabla = 'contratos' AND a.registro_id = p_contrato_id)
      OR (a.tabla <> 'contratos'
          AND coalesce(a.valor_nuevo ->> 'contrato_id', a.valor_anterior ->> 'contrato_id') = p_contrato_id::text)
    )
  ORDER BY a.creado_en DESC, a.id DESC
  LIMIT 200;
$$;

ALTER TABLE public.auditoria ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS auditoria_select_encargado ON public.auditoria;
CREATE POLICY auditoria_select_encargado ON public.auditoria
  FOR SELECT TO authenticated
  USING (public.es_encargado());

REVOKE ALL ON public.auditoria FROM anon;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON public.auditoria FROM PUBLIC, authenticated;
GRANT SELECT ON public.auditoria TO authenticated;

